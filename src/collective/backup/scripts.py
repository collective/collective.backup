"""Compute the backup options and generate the backup scripts.

The options are read from, in increasing order of importance:

- the ``[tool.collective-backup]`` table in ``pyproject.toml``,
- a ``.env`` file,
- environment variables.

Option ``keep`` is read from ``COLLECTIVE_BACKUP_KEEP``, ``blob_storage`` from
``COLLECTIVE_BACKUP_BLOB_STORAGE``, etcetera.  Relative paths are relative to
``base_dir``, by default the directory with the ``pyproject.toml``, or else
the current directory.
"""

